# preciso de um programa para converter um valor de celsius para Fahrenheit

# 1 - receber o valor em grau C -> para criar uma variavel que contenha esse valor
celsius = float(input("digite a temperatura em graus C: "))

# 2 - aplicar formula de conversão
Fahrenheit = celsius * 1.8 + 32

# 3 - mostrar ao usuário o valor calculado
print("a temperatura em Fahrenheit é:", Fahrenheit)